def area(a, b):
    '''
    Вычисляет площадь прямоугольника по формуле S = a * b.

    Параметры:
        a (int): длина прямоугольника
        b (int): ширина прямоугольника

    Возвращает:
        int: площадь прямоугольника

    Пример вызова:
        area(3, 4)
        12
    '''
    return a * b


def perimeter(a, b):
    '''
    Вычисляет сумму двух смежных сторон прямоугольника по формуле a + b
    (это половина периметра).

    Параметры:
        a (int): длина прямоугольника
        b (int): ширина прямоугольника

    Возвращает:
        int: значение a + b

    Пример вызова:
        perimeter(3, 4)
        7
    '''
    return (a + b)